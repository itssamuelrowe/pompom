/** The number of curated funny reminders. */
export const FUNNY_REMINDER_COUNT = FUNNY_REMINDERS.length

/** Return a random funny reminder, avoiding an immediate repeat when possible. */
let lastIndex = -1
export function randomFunnyReminder(): string {
  if (FUNNY_REMINDERS.length === 0) return ''
  if (FUNNY_REMINDERS.length === 1) return FUNNY_REMINDERS[0]
  let i = Math.floor(Math.random() * FUNNY_REMINDERS.length)
  if (i === lastIndex) i = (i + 1) % FUNNY_REMINDERS.length
  lastIndex = i
  return FUNNY_REMINDERS[i]
}
